            // ── Setup stats builder ────────────────────────────
            function buildSetupStats(trades) {
                var map = {};
                trades.forEach(function(t) {
                    var s = (t.setupType && t.setupType.trim()) ? t.setupType.trim() : 'No Strategy';
                    if (_state.hideNoSetup && s === 'No Strategy') return;
                    if (!map[s]) map[s] = { name:s, count:0, pnl:0, wins:0, losses:0,
                                            sumWins:0, sumLosses:0, largestWin:0, largestLoss:0 };
                    var p = parseFloat(t.pnl) || 0;
                    map[s].count++;
                    map[s].pnl += p;
                    if (p > 0) { map[s].wins++; map[s].sumWins += p; if(p > map[s].largestWin) map[s].largestWin = p; }
                    else if (p < 0) { map[s].losses++; map[s].sumLosses += p; if(p < map[s].largestLoss) map[s].largestLoss = p; }
                });
                return Object.keys(map).map(function(s) {
                    var m = map[s];
                    m.avgPnl    = m.count  ? m.pnl / m.count : 0;
                    m.winRate   = m.count  ? m.wins / m.count * 100 : 0;
                    m.avgWin    = m.wins   ? m.sumWins / m.wins : 0;
                    m.avgLoss   = m.losses ? m.sumLosses / m.losses : 0;
                    m.expectancy= m.count  ? (m.winRate/100 * m.avgWin + (1 - m.winRate/100) * m.avgLoss) : 0;
                    m.profitFactor = m.sumLosses ? Math.abs(m.sumWins / m.sumLosses) : (m.sumWins > 0 ? Infinity : 0);
                    return m;
                });
            }

            function rankSetups(stats) {
                var filtered = stats.filter(function(s){ return s.count >= _state.minSample; });
                return filtered.slice().sort(function(a, b) {
                    switch (_state.rankBy) {
                        case 'win-rate':      return b.winRate - a.winRate;
                        case 'profit-factor': return (isFinite(b.profitFactor)?b.profitFactor:1e9) - (isFinite(a.profitFactor)?a.profitFactor:1e9);
                        case 'expectancy':    return b.expectancy - a.expectancy;
                        case 'trade-count':   return b.count - a.count;
                        default:              return b.pnl - a.pnl;
                    }
                });
            }

            function getRankValue(s) {
                switch (_state.rankBy) {
                    case 'win-rate':      return fmtPct(s.winRate);
                    case 'profit-factor': return fmtPF(s.profitFactor);
                    case 'expectancy':    return fmt$(s.expectancy);
                    case 'trade-count':   return s.count + ' trades';
                    default:              return fmt$(s.pnl);
                }
            }
            function getRankValueClass(s) {
                switch (_state.rankBy) {
                    case 'win-rate':      return s.winRate >= 50 ? 'su-lb-pos' : 'su-lb-neg';
                    case 'profit-factor': return s.profitFactor >= 1 ? 'su-lb-pos' : 'su-lb-neg';
                    case 'expectancy':    return suPnlCls(s.expectancy);
                    case 'trade-count':   return 'su-lb-neu';
                    default:              return suPnlCls(s.pnl);
                }
            }

