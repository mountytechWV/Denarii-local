            // ── Utilities ──────────────────────────────────────
            function fmt$(n) {
                if (n == null || isNaN(n)) return '—';
                var abs = Math.abs(n);
                var s = abs >= 10000 ? '$' + Math.round(abs).toLocaleString()
                      : abs >= 1000  ? '$' + Math.round(abs).toLocaleString()
                      : '$' + abs.toFixed(2);
                return (n < 0 ? '-' : '') + s;
            }
            function fmtPct(n) { return (n == null || isNaN(n)) ? '—' : n.toFixed(1) + '%'; }
            function fmtPF(n)  { return (!n || !isFinite(n)) ? '—' : n.toFixed(2); }
            function fmtNum(n) { return (n == null || isNaN(n)) ? '—' : n.toLocaleString(); }
            function pnlCls(n) {
                if (!n || n === 0) return 'snap-kpi-neutral';
                return n > 0 ? 'snap-kpi-positive' : 'snap-kpi-negative';
            }
            function suPnlCls(n) {
                if (!n || n === 0) return 'su-lb-neu';
                return n > 0 ? 'su-lb-pos' : 'su-lb-neg';
            }
            function esc(s) {
                return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
            }

